"""Build assets/stk-sample.js from Krackhardt's high-tech managers data.

Source rows: Krackhardt, D. (1987). Cognitive social structures. Social Networks 9(2):109-134.
21 managers of a small high-tech manufacturing firm; advice, friendship and reports-to ties plus
age, tenure, level and department. The copy used here is the one shipped in the CRAN package
NetData 0.3 (GPL-2), file data/kracknets.rda, read from the CRAN GitHub mirror:
  https://raw.githubusercontent.com/cran/NetData/master/data/kracknets.rda
(archive tarball: https://cran.r-project.org/src/contrib/Archive/NetData/NetData_0.3.tar.gz).
NetData's own help page describes a different Krackhardt study (a union campaign at "Silicon
Systems"); the rows it ships are the 21-manager data (190 advice, 102 friendship, 20 reports-to
arcs), which is what this builder checks before writing anything.

Run:  python3 materials/build-stk-sample.py [path/to/kracknets.rda]
Needs: pyreadr (pip install pyreadr). Writes JSON with json.dumps, never string interpolation.
"""
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
URL = "https://raw.githubusercontent.com/cran/NetData/master/data/kracknets.rda"


def main():
    import pyreadr  # imported here so the reference script never needs it

    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "kracknets.rda")
    if not os.path.exists(path):
        urllib.request.urlretrieve(URL, path)
    r = pyreadr.read_r(path)
    d = r["krack_full_data_frame"]
    d = d[d.ego != d.alter]
    att = r["attributes"]
    n = len(att)
    assert n == 21, n

    def lists(col):
        out = [[] for _ in range(n)]
        for e, a in d[d[col] == 1][["ego", "alter"]].values:
            out[int(e) - 1].append(int(a))
        return [sorted(x) for x in out]

    advice = lists("advice_tie")
    friendship = lists("friendship_tie")
    reports = lists("reports_to_tie")
    assert sum(map(len, advice)) == 190
    assert sum(map(len, friendship)) == 102
    assert sum(map(len, reports)) == 20
    reports_to = [x[0] if x else 0 for x in reports]

    data = {
        "source": "Krackhardt (1987), Cognitive social structures, Social Networks 9(2):109-134. "
                  "21 managers of a small high-tech manufacturing firm. Rows as shipped in CRAN NetData 0.3 "
                  "(kracknets.rda, GPL-2).",
        "n": n,
        "level": [int(v) for v in att.LEVEL.values],
        "dept": [int(v) for v in att.DEPT.values],
        "age": [int(v) for v in att.AGE.values],
        "tenure": [round(float(v), 1) for v in att.TENURE.values],
        "reportsTo": reports_to,
        "advice": advice,
        "friendship": friendship,
    }
    js = ("/* stk-sample.js - generated by materials/build-stk-sample.py; do not edit by hand.\n"
          " * Krackhardt (1987) high-tech managers: 21 people, ids 1-21. advice[i-1] lists the managers\n"
          " * that manager i goes to for advice; friendship[i-1] the managers i names as friends;\n"
          " * reportsTo[i-1] is i's boss (0 = nobody). Level 1 = CEO, 2 = vice president, 3 = manager. */\n"
          "window.STK_SAMPLE = " + json.dumps(data, separators=(",", ":")) + ";\n")
    with open(os.path.join(REPO, "assets", "stk-sample.js"), "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote assets/stk-sample.js", len(js), "bytes")


if __name__ == "__main__":
    main()
